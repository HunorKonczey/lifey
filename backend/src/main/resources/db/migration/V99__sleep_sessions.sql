-- Sleep sessions imported from the health store (docs/integrations/89 M2, G2.1, D-G7):
-- one row per sleep session (a night, or a nap), whatever recorded it - a Garmin
-- watch through Garmin Connect, an Apple Watch, a phone.
--
-- A synced entity shaped like weight_entries: soft delete via deleted_at, delta feed
-- ordered by (updated_at, id).
--
-- The stage minutes are nullable: a source without stages (duration only) leaves
-- them null, never 0 - a 0 would read as "no deep sleep at all". asleep_minutes is
-- the time actually asleep, which can be less than ended_at - started_at.
--
-- No date column: D-G7 attributes a session to the local date of its *end* (the
-- wake-up date), and only the client knows the local time zone, so the client
-- derives it from ended_at.
--
-- health_record_id is the store's record id, the import dedupe key (same idea as
-- workout_sessions' D-G3 index in V97): the same record imported twice for one user
-- is refused. Soft-deleted rows still count, so a night the user deleted is not
-- imported again. Nullable, and Postgres treats nulls as distinct, so a session with
-- no store id (none exist yet) is not blocked by the constraint.
create table sleep_sessions (
    id               bigint generated by default as identity primary key,
    user_id          bigint      not null references users (id) on delete cascade,
    started_at       timestamptz not null,
    ended_at         timestamptz not null,
    asleep_minutes   integer,
    deep_minutes     integer,
    light_minutes    integer,
    rem_minutes      integer,
    awake_minutes    integer,
    source_app_name  varchar(64),
    health_record_id varchar(128),
    created_at       timestamptz not null default now(),
    updated_at       timestamptz not null default now(),
    deleted_at       timestamptz,
    constraint sleep_sessions_ended_after_started_ck check (ended_at > started_at),
    constraint sleep_sessions_minutes_ck check (
        (asleep_minutes is null or asleep_minutes >= 0)
        and (deep_minutes is null or deep_minutes >= 0)
        and (light_minutes is null or light_minutes >= 0)
        and (rem_minutes is null or rem_minutes >= 0)
        and (awake_minutes is null or awake_minutes >= 0)),
    constraint sleep_sessions_user_id_health_record_id_unique unique (user_id, health_record_id)
);

-- Covers the user_id foreign key too, and serves the newest-first history list.
create index sleep_sessions_user_id_ended_at_idx on sleep_sessions (user_id, ended_at);
create index sleep_sessions_updated_at_idx on sleep_sessions (updated_at, id);
