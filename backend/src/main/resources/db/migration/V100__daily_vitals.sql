-- Daily vitals imported from the health store (docs/integrations/89 M3, G3.1, D-G8):
-- one row per user per day with the resting heart rate and the heart rate
-- variability, the same shape as daily_step_counts (V16, V30).
--
-- Both values are nullable: a day may have only one of them (a watch that measures
-- resting HR but not HRV), but a row with neither means nothing and is refused.
--
-- hrv_method records how the HRV was measured. iOS stores SDNN, Health Connect
-- stores RMSSD; the two are not comparable, so the method is kept and the client
-- never mixes them in one trend. It is set exactly when hrv_ms is.
--
-- The bounds are wide sanity checks, not physiology: they only keep a unit mix-up
-- (seconds instead of milliseconds, say) out of the trend.
create table daily_vitals (
    id          bigint generated by default as identity primary key,
    user_id     bigint      not null references users (id) on delete cascade,
    entry_date  date        not null,
    resting_hr  integer,
    hrv_ms      double precision,
    hrv_method  varchar(8),
    updated_at  timestamptz not null default now(),
    deleted_at  timestamptz,
    constraint daily_vitals_user_id_entry_date_unique unique (user_id, entry_date),
    constraint daily_vitals_resting_hr_ck check (resting_hr is null or resting_hr between 20 and 250),
    constraint daily_vitals_hrv_ms_ck check (hrv_ms is null or (hrv_ms > 0 and hrv_ms <= 1000)),
    constraint daily_vitals_hrv_method_ck check (hrv_method in ('SDNN', 'RMSSD')),
    constraint daily_vitals_hrv_method_with_value_ck check ((hrv_ms is null) = (hrv_method is null)),
    constraint daily_vitals_some_value_ck check (resting_hr is not null or hrv_ms is not null)
);

-- The unique (user_id, entry_date) index already covers the user_id foreign key.
create index daily_vitals_updated_at_idx on daily_vitals (updated_at, id);
